const STRINGS: Record<Lang, Strings> = { en, vi };

export type StringKey = keyof Strings;

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Current language + a bound translate function for components. */
export function useT() {
  const lang = useProgressStore((s) => s.lang);
  return { lang, t: (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars) };
}
